"""
PROBLEMA: 
Calcular a média dos números dados pelo usuário
"""
# - Digitar o primeiro número (ED)
n1 = input("Digite o primeiro número: ")
n1 = float(n1)
# - Digitar o segundo número (ED)
n2 = input("Digite o segundo número: ")
n2 = float(n2)
# - Digitar o terceiro número (ED)
n3 = input("Digite o terceiro número: ")
n3 = float(n3)
# - Calcular a média dos números (PD)
m = (n1 + n2 + n3) / 3
# - Exibir o resultado (SD)
print("Média: ", m)
